"""
ARES X Red Module — Pentest Report Generator
Generates executive + technical reports from engagement findings.
"""
from __future__ import annotations

from datetime import datetime, timezone
from typing import Optional

from aresx.red.cvss_calc import Finding, Severity, findings_summary, sort_findings_by_severity


def generate_executive_summary(
    engagement_name: str,
    findings: list[Finding],
    scope_description: str = "",
    engagement_dates: str = "",
) -> str:
    """
    Generate a non-technical executive summary — for leadership/stakeholders.
    Focused on business risk, not technical detail.
    """
    stats = findings_summary(findings)
    critical = stats["by_severity"].get("Critical", 0)
    high = stats["by_severity"].get("High", 0)
    medium = stats["by_severity"].get("Medium", 0)
    low = stats["by_severity"].get("Low", 0)

    risk_posture = "CRITICAL" if critical > 0 else "HIGH" if high > 0 else \
                   "MODERATE" if medium > 0 else "LOW"

    lines = [
        f"# Executive Summary — {engagement_name}",
        "",
        f"**Engagement dates:** {engagement_dates or 'N/A'}",
        f"**Scope:** {scope_description or 'See detailed scope document'}",
        f"**Overall risk posture:** {risk_posture}",
        "",
        "## Summary",
        "",
        f"During this engagement, the assessment team identified **{stats['total']} findings** "
        f"across the tested scope. Of these, **{critical} were rated Critical** and "
        f"**{high} were rated High** severity, requiring immediate attention.",
        "",
        "## Risk Breakdown",
        "",
        "| Severity | Count |",
        "|----------|-------|",
        f"| Critical | {critical} |",
        f"| High     | {high} |",
        f"| Medium   | {medium} |",
        f"| Low      | {low} |",
        "",
    ]

    if critical > 0:
        lines += [
            "## Immediate Action Required",
            "",
            "The following critical findings represent an immediate and significant "
            "risk to the organization and should be remediated as a priority:",
            "",
        ]
        crit_findings = [f for f in findings if f.severity == Severity.CRITICAL]
        for f in crit_findings[:5]:
            lines.append(f"- **{f.title}** ({f.affected_asset})")
        lines.append("")

    lines += [
        "## Recommendation",
        "",
        "It is recommended that the organization prioritize remediation of Critical "
        "and High severity findings within 30 days, and schedule a retest to verify "
        "fixes before this risk window closes.",
        "",
        f"*Report generated by ARES X Red Module — {datetime.now(timezone.utc).strftime('%Y-%m-%d')}*",
    ]

    return "\n".join(lines)


def generate_technical_report(
    engagement_name: str,
    findings: list[Finding],
    tester_name: str = "",
    methodology: str = "",
) -> str:
    """
    Generate a full technical report with per-finding detail —
    description, impact, PoC, remediation, references.
    """
    sorted_findings = sort_findings_by_severity(findings)
    stats = findings_summary(findings)

    lines = [
        f"# Technical Report — {engagement_name}",
        "",
        f"**Tester:** {tester_name or 'N/A'}",
        f"**Report date:** {datetime.now(timezone.utc).strftime('%Y-%m-%d')}",
        f"**Total findings:** {stats['total']}",
        f"**Average CVSS score:** {stats['avg_cvss_score']}",
        "",
    ]

    if methodology:
        lines += ["## Methodology", "", methodology, ""]

    lines += ["## Findings", ""]

    for i, f in enumerate(sorted_findings, 1):
        lines += [
            f"### {i}. {f.title}",
            "",
            f"**Severity:** {f.severity.value}" +
            (f" (CVSS {f.cvss_score})" if f.cvss_score else ""),
            f"**Status:** {f.status}",
            f"**Affected asset:** {f.affected_asset}",
        ]
        if f.cvss_vector:
            lines.append(f"**CVSS vector:** `{f.cvss_vector}`")
        if f.cwe_id:
            lines.append(f"**CWE:** {f.cwe_id}")
        lines += [
            "",
            "**Description**",
            "",
            f.description or "_No description provided._",
            "",
        ]
        if f.proof_of_concept:
            lines += [
                "**Proof of Concept**",
                "",
                "```",
                f.proof_of_concept,
                "```",
                "",
            ]
        lines += [
            "**Remediation**",
            "",
            f.remediation or "_No remediation guidance provided._",
            "",
        ]
        if f.references:
            lines.append("**References**")
            for ref in f.references:
                lines.append(f"- {ref}")
            lines.append("")
        lines.append("---")
        lines.append("")

    return "\n".join(lines)


def generate_attack_narrative(kill_chain_stages: list[dict], target: str = "") -> str:
    """
    Generate a narrative walkthrough of an attack path — how the assessment
    team moved through the kill chain, for inclusion in the technical report.
    """
    lines = [
        f"## Attack Path Narrative{f' — {target}' if target else ''}",
        "",
    ]

    if not kill_chain_stages:
        lines.append("_No multi-stage attack path was demonstrated in this engagement._")
        return "\n".join(lines)

    for i, stage in enumerate(kill_chain_stages, 1):
        tactic = stage.get("tactic", "Unknown")
        technique = stage.get("technique_name", stage.get("technique_id", ""))
        details = stage.get("details", stage.get("description", ""))
        lines += [
            f"**Step {i}: {tactic}** ({stage.get('technique_id', '')})",
            "",
            f"{technique}: {details}",
            "",
        ]

    return "\n".join(lines)


def export_findings_json(findings: list[Finding]) -> dict:
    """Structured JSON export of all findings."""
    return {
        "total": len(findings),
        "summary": findings_summary(findings),
        "findings": [
            {
                "id": f.finding_id, "title": f.title, "description": f.description,
                "severity": f.severity.value, "cvss_score": f.cvss_score,
                "cvss_vector": f.cvss_vector, "affected_asset": f.affected_asset,
                "status": f.status, "cwe_id": f.cwe_id,
                "remediation": f.remediation, "references": f.references,
                "discovered_at": f.discovered_at, "tags": f.tags,
            }
            for f in findings
        ],
    }


def generate_full_report(
    engagement_name: str,
    findings: list[Finding],
    scope_description: str = "",
    engagement_dates: str = "",
    tester_name: str = "",
    methodology: str = "",
    kill_chain_stages: Optional[list[dict]] = None,
) -> dict:
    """
    Generate the complete report package — executive summary + technical
    report + attack narrative + JSON export, all in one call.
    """
    exec_summary = generate_executive_summary(
        engagement_name, findings, scope_description, engagement_dates
    )
    tech_report = generate_technical_report(
        engagement_name, findings, tester_name, methodology
    )
    narrative = generate_attack_narrative(kill_chain_stages or [], engagement_name)
    json_export = export_findings_json(findings)

    full_markdown = exec_summary + "\n\n---\n\n" + tech_report
    if kill_chain_stages:
        full_markdown += "\n\n---\n\n" + narrative

    return {
        "executive_summary_md": exec_summary,
        "technical_report_md": tech_report,
        "attack_narrative_md": narrative,
        "full_report_md": full_markdown,
        "json_export": json_export,
    }
